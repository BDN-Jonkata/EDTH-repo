"""Export the preset scenarios (at their default seeds) to ui/viewer/scenarios.js.

The viewer uses these when it is opened without serve.py; with serve.py it asks the generator for
any preset and seed. Ground truth is not exported: the simulation derives it from the same motion models.

    python seeder/export_scenarios.py
"""
from __future__ import annotations

import json
from pathlib import Path

import scenario as sc

ROOT = Path(__file__).parent.parent
OUT = ROOT / "ui" / "viewer" / "scenarios.js"


def main():
    out = {}
    for path in sorted((ROOT / "scenarios").glob("*.json")):
        config = json.loads(path.read_text(encoding="utf-8"))
        scenario, _ = sc.generate(config, truth_dt=1.0)
        out[path.stem] = scenario
    body = json.dumps(out, separators=(",", ":"))
    OUT.write_text(
        "// Generated by seeder/export_scenarios.py from scenarios/*.json. Do not edit by hand.\n"
        "(function (g) {\n  var SCENARIOS = " + body + ";\n"
        "  g.SCENARIOS = SCENARIOS;\n  if (typeof module !== 'undefined') module.exports = SCENARIOS;\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n",
        encoding="utf-8",
    )
    print("Wrote %s (%s)" % (OUT, ", ".join(out)))


if __name__ == "__main__":
    main()
